-------------------------------------------------------------------------------- Raport 3 (C minim 7) --------------------------------------------------------------------------------

-- Top 5 biserici cu cele mai mari vanzari din luna cu cele mai multe evenimente

CREATE OR REPLACE PROCEDURE raport_biserica_cu_cele_mai_mari_vanzari_din_luna_cu_cele_mai_multe_evenimente (
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        WITH EvenimenteLuna AS (
            SELECT
                TO_CHAR(E.Data, 'MM') AS Luna,
                TO_CHAR(E.Data, 'YYYY') AS An,
                COUNT(E.IDEveniment) AS NumarEvenimente
            FROM
                Evenimente E
            GROUP BY
                TO_CHAR(E.Data, 'MM'), TO_CHAR(E.Data, 'YYYY') -- 1
            ORDER BY
                NumarEvenimente DESC
            FETCH FIRST 1 ROWS ONLY
        ),
        VanzariLuna AS (
            SELECT 
                TO_CHAR(V.Data, 'MM') AS Luna,
                TO_CHAR(V.Data, 'YYYY') AS An,
                B.IDBiserica,
                B.Nume AS Biserica,
                SUM(V.Cantitate * R.Cost) AS SumaTotala,
                COUNT(V.IDVanzare) AS NumarVanzari
            FROM
                Vanzari V
            JOIN
                Enoriasi E ON V.IDEnorias = E.IDEnorias -- 2
            JOIN
                Preoti P ON E.IDPreot = P.IDPreot -- 3
            JOIN
                Biserici B ON P.IDBiserica = B.IDBiserica -- 4
            JOIN    
                Resurse R ON V.IDResursa = R.IDResursa -- 5
            GROUP BY
                TO_CHAR(V.Data, 'MM'), TO_CHAR(V.Data, 'YYYY'), B.IDBiserica, B.Nume -- 6
        ),
        MaxVanzariLuna AS (
            SELECT 
                VL.Luna,
                VL.An,
                VL.Biserica,
                VL.SumaTotala,
                VL.NumarVanzari,
                RANK() OVER (PARTITION BY VL.Luna, VL.An ORDER BY VL.SumaTotala DESC) AS Rnk
            FROM
                VanzariLuna VL
            JOIN
                EvenimenteLuna EL ON VL.Luna = EL.Luna AND VL.An = EL.An -- 7
        )
        SELECT 
            Luna,
            An,
            Biserica,
            SumaTotala,
            NumarVanzari
        FROM
            MaxVanzariLuna
        WHERE
            Rnk > 0 AND Rnk <= 5 -- 8
        ORDER BY
            An, Luna, SumaTotala DESC;
END;
