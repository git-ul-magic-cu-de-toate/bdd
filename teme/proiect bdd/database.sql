-------------------------------------------------------------------------------- Raport 1 (C minim 4) --------------------------------------------------------------------------------

-- Top 10 preoti care au cei mai multi enoriași care au donat
CREATE OR REPLACE PROCEDURE raport_top10_preoti (
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        SELECT
            B.Nume AS Biserica,
            P.Nume,
            P.Prenume,
            COUNT(E.IDEnorias) AS NumarEnoriasi,
            SUM(D.Suma) AS SumaTotalaDonata
        FROM
            Biserici B
        JOIN
            Preoti P ON B.IDBiserica = P.IDBiserica -- 1
        JOIN
            Enoriasi E ON P.IDPreot = E.IDPreot -- 2
        JOIN
            Donatii D ON E.IDEnorias = D.IDEnorias -- 3
        GROUP BY
            B.Nume, P.Nume, P.Prenume -- 4
        ORDER BY
            COUNT(E.IDEnorias) DESC
        FETCH FIRST 10 ROWS ONLY;
END;
