-------------------------------------------------------------------------------- Raport 2 (C minim 6) --------------------------------------------------------------------------------

-- Top 10 biserici cu cele mai mari donatii din luna cu cele mai multe evenimente

CREATE OR REPLACE PROCEDURE raport_biserica_cu_cele_mai_mari_donatii_din_luna_cu_cele_mai_multe_evenimente (
    p_cursor OUT SYS_REFCURSOR
) AS
BEGIN
    OPEN p_cursor FOR
        WITH EvenimenteLuna AS (
            SELECT
                TO_CHAR(E.Data, 'MM') AS Luna,
                TO_CHAR(E.Data, 'YYYY') AS An,
                COUNT(E.IDEveniment) AS NumarEvenimente
            FROM
                Evenimente E
            GROUP BY
                TO_CHAR(E.Data, 'MM'), TO_CHAR(E.Data, 'YYYY') -- 1
            ORDER BY
                NumarEvenimente DESC
            FETCH FIRST 1 ROWS ONLY
        ),
        DonatiiLuna AS (
            SELECT 
                TO_CHAR(D.Data, 'MM') AS Luna,
                TO_CHAR(D.Data, 'YYYY') AS An,
                B.IDBiserica,
                B.Nume AS Biserica,
                SUM(D.Suma) AS SumaTotala,
                COUNT(D.IDDonatie) AS NumarDonatii
            FROM
                Donatii D
            JOIN
                Enoriasi E ON D.IDEnorias = E.IDEnorias -- 2
            JOIN
                Preoti P ON E.IDPreot = P.IDPreot -- 3
            JOIN
                Biserici B ON P.IDBiserica = B.IDBiserica -- 4
            GROUP BY
                TO_CHAR(D.Data, 'MM'), TO_CHAR(D.Data, 'YYYY'), B.IDBiserica, B.Nume -- 5
        ),
        MaxDonatiiLuna AS (
            SELECT 
                DL.Luna,
                DL.An,
                DL.Biserica,
                DL.SumaTotala,
                DL.NumarDonatii,
                RANK() OVER (PARTITION BY DL.Luna, DL.An ORDER BY DL.SumaTotala DESC) AS Rnk
            FROM
                DonatiiLuna DL
            JOIN
                EvenimenteLuna EL ON DL.Luna = EL.Luna AND DL.An = EL.An -- 6
        )
        SELECT 
            Luna,
            An,
            Biserica,
            SumaTotala,
            NumarDonatii
        FROM
            MaxDonatiiLuna
        WHERE
            Rnk > 0 AND Rnk <= 10 -- 7
        ORDER BY
            An, Luna, SumaTotala DESC;
END;
