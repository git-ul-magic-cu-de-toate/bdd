-------------------------------------------------------------------------------- Tabele --------------------------------------------------------------------------------

CREATE TABLE Biserici (
    IDBiserica NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nume VARCHAR2(50) NOT NULL,
    Adresa VARCHAR2(75),
    DataConstructiei DATE,
    Tip VARCHAR2(20) CHECK (Tip IN ('Ortodoxă', 'Catolică', 'Protestantă', 'Penticostală', 'Baptistă', 'Greco-Catolică', 'Romano-Catolică', 'Neo-Protestantă'))
);

CREATE TABLE Preoti (
    IDPreot NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nume VARCHAR2(20) NOT NULL,
    Prenume VARCHAR2(20) NOT NULL,
    IDBiserica NUMBER NOT NULL,

    FOREIGN KEY (IDBiserica) REFERENCES Biserici(IDBiserica)
);

CREATE TABLE Enoriasi (
    IDEnorias NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nume VARCHAR2(20) NOT NULL,
    Prenume VARCHAR2(20) NOT NULL,
    IDPreot NUMBER NOT NULL,

    FOREIGN KEY (IDPreot) REFERENCES Preoti(IDPreot)
);

CREATE TABLE Donatii (
    IDDonatie NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDEnorias NUMBER NOT NULL,
    Suma NUMBER(10, 2) CHECK (Suma > 0),
    Data DATE DEFAULT SYSDATE,

    FOREIGN KEY (IDEnorias) REFERENCES Enoriasi(IDEnorias)
);

CREATE TABLE Evenimente (
    IDEveniment NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Tip VARCHAR2(20) CHECK (Tip IN ('Slujbă', 'Înmormântare', 'Cununie', 'Botez', 'Împărtășanie')),
    Data DATE NOT NULL,
    IDBiserica NUMBER NOT NULL,

    FOREIGN KEY (IDBiserica) REFERENCES Biserici(IDBiserica)
);

CREATE TABLE Resurse (
    IDResursa NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Nume VARCHAR2(50) NOT NULL,
    Cost NUMBER(10, 2) CHECK (Cost >= 0),
    IDBiserica NUMBER NOT NULL,

    FOREIGN KEY (IDBiserica) REFERENCES Biserici(IDBiserica)
);

CREATE TABLE Vanzari (
    IDVanzare NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDEnorias NUMBER NOT NULL,
    IDResursa NUMBER NOT NULL,
    Cantitate NUMBER CHECK (Cantitate > 0),
    Data DATE DEFAULT SYSDATE,

    FOREIGN KEY (IDEnorias) REFERENCES Enoriasi(IDEnorias),
    FOREIGN KEY (IDResursa) REFERENCES Resurse(IDResursa)
);

